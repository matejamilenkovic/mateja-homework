num = int (input('enter a number '))
if num == 100:
    print('')
if num > 100:
    print('bigger than 100')
if num < 100: 
    print('less than 100')
if num <= 100 : 
    print('less than or equal to 100')
if num >= 100 : 
    print('greater than or equal to 100')
if num != 100 : 
    print('not equal to 100')